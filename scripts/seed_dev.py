# Public dev defaults (README / .env.example / CLAUDE.md): never valid in production.
DEV_DEFAULT_PASSWORDS = frozenset({"Admin@1234", "Super@1234"})
MIN_PROD_PASSWORD_LEN = 12
PASSWORD_VARS = ("SEED_ADMIN_PASSWORD", "SEED_SUPERADMIN_PASS")


def production_mode(env: Mapping[str, str] = os.environ) -> bool:
    return (
        env.get("APP_ENV", "").strip().lower() in {"production", "prod"}
        or env.get("SEED_ENFORCE_PROD_CREDENTIALS", "").strip() == "1"
    )


def production_credential_errors(env: Mapping[str, str] = os.environ) -> list[str]:
    """Problems with the seed passwords for a production run (names only, never values)."""
    errors = []
    for var in PASSWORD_VARS:
        value = env.get(var, "")
        if not value.strip():
            errors.append(f"{var} não definido no ambiente do container")
        elif value in DEV_DEFAULT_PASSWORDS:
            errors.append(f"{var} usa a senha padrão de desenvolvimento (pública)")
        elif len(value) < MIN_PROD_PASSWORD_LEN:
            errors.append(f"{var} precisa de pelo menos {MIN_PROD_PASSWORD_LEN} caracteres")
    return errors


def ensure_safe_credentials(env: Mapping[str, str] = os.environ) -> None:
    """Raises SystemExit(3) in production mode when the seed passwords are unsafe."""
    if not production_mode(env):
        return
    errors = production_credential_errors(env)
    if errors:
        msg = "\n".join(f"  - {e}" for e in errors)
        raise SystemExit(f"✗ Seed recusado em produção:\n{msg}")


def _shown(password: str) -> str:
    return "********" if production_mode() else password


# ── Demo plant (Planta Manaus) ────────────────────────────────────────────────

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_PLANT_MAP = os.path.join(REPO_ROOT, "edge", "config", "plant.json")
PROTOCOL = {"opcua": "opc_ua", "modbus": "modbus_tcp"}
COMPONENT_TYPE_ALIASES = {"servo_motor": "servo", "contactor": "other"}


def load_plant_map(env: Mapping[str, str] = os.environ) -> "dict | None":
    import json
    if env.get("SEED_DEMO_PLANT", "1").strip() == "0":
        return None
    path = env.get("SEED_PLANT_MAP") or DEFAULT_PLANT_MAP
    if not os.path.exists(path):
        return None
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def tag_address(tag: dict) -> str:
    """Same Tag.address format as edge/src/provision.py (_address_string)."""
    if isinstance(tag.get("address"), str):
        return tag["address"]
    area = {"discrete": "di", "coil": "co", "input": "ir"}.get(tag.get("register_type"), "hr")
    dt = f":{tag['data_type_plc']}" if tag.get("data_type_plc") and area in ("hr", "ir") else ""
    return f"unit={tag.get('unit_id', 1)};{area}={tag['address']}{dt}"


def _nominal(life: "dict | None") -> dict:
    return {k: v for k, v in (life or {}).items() if k in ("cycles", "hours", "starts") and v}


async def seed_demo_plant(db, tenant_id: str, doc: dict) -> dict:
    """Creates (or completes) the plant described by the gateway map for tenant_id. Commits."""
    from datetime import datetime, timezone
    from sqlalchemy import select
    from src.models import (Component, ComponentType, DataType, Line, Machine, Plant, Position,
                            ProtocolType, SemanticRole, Tag)

    stats = {"created": 0, "existing": 0}

    async def get_or_create(model, where: dict, values: dict):
        q = select(model)
        for k, v in where.items():
            q = q.where(getattr(model, k) == v)
        row = (await db.execute(q.limit(1))).scalar_one_or_none()
        if row is not None:
            stats["existing"] += 1
            return row
        row = model(**where, **values)
        db.add(row)
        await db.flush()
        stats["created"] += 1
        return row

    assets = doc["assets"]
    p = assets["plant"]
    plant = await get_or_create(Plant, {"tenant_id": tenant_id, "name": p["name"]},
                                {"timezone": p.get("timezone") or "America/Sao_Paulo", "address": p.get("address")})
    machines: dict = {}
    positions: dict = {}
    for ln in assets["lines"]:
        line = await get_or_create(Line, {"tenant_id": tenant_id, "plant_id": plant.id, "name": ln["name"]}, {})
        for m in ln["machines"]:
            machine = await get_or_create(Machine, {"tenant_id": tenant_id, "line_id": line.id, "name": m["name"]},
                                          {"model": m.get("model"), "serial_number": m.get("serial_number")})
            machines[(ln["name"], m["name"])] = machine
            for pos in m.get("positions", []):
                ctype = ComponentType(COMPONENT_TYPE_ALIASES.get(pos["component_type"], pos["component_type"]))
                position = await get_or_create(
                    Position, {"tenant_id": tenant_id, "machine_id": machine.id, "name": pos["name"]},
                    {"component_type": ctype, "cycles_per_part": max(1, int(round(pos.get("cycles_per_part") or 1)))})
                positions[(ln["name"], m["name"], pos["name"])] = (position, pos)
                comp = pos.get("component")
                if comp:
                    c = await get_or_create(
                        Component, {"tenant_id": tenant_id, "serial_number": comp["serial_number"]},
                        {"component_type": ctype, "manufacturer": comp.get("manufacturer"),
                         "model": comp.get("model"), "nominal_life": _nominal(comp.get("nominal_life"))})
                    occupied = (await db.execute(select(Component.id).where(
                        Component.position_id == position.id, Component.removed_at.is_(None)))).scalar_one_or_none()
                    if c.position_id is None and c.removed_at is None and occupied is None:
                        c.position_id = c.last_position_id = position.id
                        c.installed_at = datetime.now(timezone.utc)
        if ln.get("output_machine") and (ln["name"], ln["output_machine"]) in machines:
            line.output_machine_id = machines[(ln["name"], ln["output_machine"])].id

    sources = {s["id"]: s for s in doc.get("sources", [])}
    key_to_tag: dict = {}
    for t in doc.get("tags", []):
        machine = machines[(t["line"], t["machine"])]
        position_id = None
        if t.get("position"):
            position_id = positions[(t["line"], t["machine"], t["position"])][0].id
        protocol = PROTOCOL.get(sources.get(t.get("source"), {}).get("protocol"), "mqtt")
        tag = await get_or_create(Tag, {"tenant_id": tenant_id, "machine_id": machine.id, "name": t["name"]}, {
            "position_id": position_id, "protocol": ProtocolType(protocol), "address": tag_address(t),
            "data_type": DataType(t.get("data_type", "float")), "unit": t.get("unit") or None,
            "semantic_role": SemanticRole(t.get("semantic_role", "analog")), "counter_max": t.get("counter_max"),
            "scale_factor": 1.0, "poll_interval_ms": t.get("poll_interval_ms", 1000),
        })
        key_to_tag[t["key"]] = tag.id
    for (position, pos) in positions.values():
        key = pos.get("counter_tag")
        if key and key in key_to_tag and position.counter_tag_id is None:
            position.counter_tag_id = key_to_tag[key]
    await db.commit()
    stats["plant_id"] = plant.id
    stats["tags"] = len(key_to_tag)
    return stats


async def seed() -> None:
    ensure_safe_credentials()

    from sqlalchemy.ext.asyncio import create_async_engine, async_sessionmaker
    from src.models import Tenant, User, UserRole
    from src.auth.security import hash_password

    engine = create_async_engine(DATABASE_URL, echo=False)
    Session = async_sessionmaker(engine, expire_on_commit=False)

    async with Session() as db:
        from sqlalchemy import select

        # ── Tenant demo ───────────────────────────────────────────
        existing = await db.execute(select(Tenant).where(Tenant.slug == TENANT_SLUG))
        if existing.scalar_one_or_none():
            print(f"⚠  Tenant '{TENANT_SLUG}' já existe. Pulando criação do tenant demo.")
        else:
            tenant = Tenant(name=TENANT_NAME, slug=TENANT_SLUG)
            db.add(tenant)
            await db.flush()

            admin = User(
                tenant_id=tenant.id,
                email=ADMIN_EMAIL,
                password_hash=hash_password(ADMIN_PASSWORD),
                name=ADMIN_NAME,
                role=UserRole.admin,
            )
            db.add(admin)
            print(f"✓  Tenant demo: {TENANT_NAME} (slug: {TENANT_SLUG})")
            print(f"   Admin: {ADMIN_EMAIL} / {_shown(ADMIN_PASSWORD)}")

        # ── Tenant "platform" para o superadmin ───────────────────
        platform_existing = await db.execute(select(Tenant).where(Tenant.slug == "platform"))
        if not platform_existing.scalar_one_or_none():
            platform_tenant = Tenant(name="Factory Monitor Platform", slug="platform")
            db.add(platform_tenant)
            await db.flush()

            superadmin = User(
                tenant_id=platform_tenant.id,
                email=SUPERADMIN_EMAIL,
                password_hash=hash_password(SUPERADMIN_PASS),
                name=SUPERADMIN_NAME,
                role=UserRole.superadmin,
            )
            db.add(superadmin)

        await db.commit()

        # ── Planta demo (Planta Manaus) ───────────────────────────
        doc = load_plant_map()
        demo = (await db.execute(select(Tenant).where(Tenant.slug == TENANT_SLUG))).scalar_one_or_none()
        if doc is None:
            print("⚠  Planta demo não criada (SEED_DEMO_PLANT=0 ou mapa da planta virtual ausente: "
                  f"{os.getenv('SEED_PLANT_MAP') or DEFAULT_PLANT_MAP}).")
        elif demo is not None:
            stats = await seed_demo_plant(db, demo.id, doc)
            print(f"✓  Planta demo '{doc['assets']['plant']['name']}': {stats['created']} criados, "
                  f"{stats['existing']} já existiam, {stats['tags']} tags.")
            print("   Ids das tags no gateway: python -m edge.src.provision (grava edge/config/plant.local.json)")

    print(f"✓  Superadmin: {SUPERADMIN_EMAIL} / {_shown(SUPERADMIN_PASS)}")
    print()
    print("Acesse /admin após login com o superadmin.")
    await engine.dispose()


if __name__ == "__main__":
    asyncio.run(seed())

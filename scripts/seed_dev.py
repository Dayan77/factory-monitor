"""
Seed script — creates a dev tenant + admin user for first-time setup and the demo plant
"Planta Manaus" (assets + semantic tags) that the edge virtual plant publishes.

Usage:
    cd server
    python ../scripts/seed_dev.py

Demo plant: built from the virtual plant's gateway map (edge/config/plant.json, generated by
`python -m edge.virtual_plant --write-map`; override with SEED_PLANT_MAP=<path>, skip with
SEED_DEMO_PLANT=0). Idempotent and name-compatible with `python -m edge.src.provision`: plant/line/
machine/position/tag are matched by name inside their parent and components by serial number, so
running provision afterwards finds these rows and writes their tag ids into the gateway map
(edge/config/plant.local.json) — the MQTT topics then carry the tag ids from this database.

Production / VPS (APP_ENV=production, or SEED_ENFORCE_PROD_CREDENTIALS=1 which
scripts/seed_remote.py always sets): refuses to run unless SEED_ADMIN_PASSWORD
and SEED_SUPERADMIN_PASS are set, are not the public dev defaults below and have
at least MIN_PROD_PASSWORD_LEN characters. Passwords are never printed there.
"""

